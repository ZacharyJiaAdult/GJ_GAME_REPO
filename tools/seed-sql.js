/* Quiltopia — builds supabase/seed.sql from js/config.js, js/rules.js, js/stitchlings.js and
   js/seed.js, so the online world plays by exactly the same rules as the demo. Used by
   tools/seed-sql.html (to copy into Supabase) and tests/sql-test.html. */
(function (root) {
  'use strict';

  // opts.plannedBlocks: how many Blocks past the first four to plan ahead, landscape included.
  // The quilt grows into them on its own as players arrive.
  function generate(opts) {
    opts = opts || {};
    const R = root.QuiltRules, ST = root.QuiltStitchlings, S = root.QuiltSeed, C = root.QUILT_CONFIG, A = R.ALLOWANCE;
    const planned = opts.plannedBlocks == null ? 48 : opts.plannedBlocks;
    const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
    const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`;
    const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

    // Everything else the database needs from the rules, as one JSON value.
    const unlocks = {};
    for (const [level, u] of Object.entries(R.LEVEL_UNLOCKS)) if (u.key.startsWith('style:')) unlocks[level] = u.key.slice(6);
    const rules = {
      lot: R.LOT, lots: R.LOTS, slotKinds: R.SLOT_KINDS,
      groups: Object.fromEntries(R.KINDS.map((k) => [k, R.PATCHES[k].group])),
      names: Object.fromEntries(R.KINDS.map((k) => [k, R.PATCHES[k].name])),
      kit: R.KIT, kitXp: R.KIT_XP, xp: R.XP, wonderButtons: R.WONDER_BUTTONS, wishDaily: R.WISH_DAILY, cozyButtons: R.COZY_BUTTONS,
      foundersNeeded: R.FOUNDERS_NEEDED, foundLevel: R.FOUND_LEVEL, shopLevel: R.SHOP_LEVEL, unlocks,
      calendar: R.CALENDAR, goals: R.GOALS, goalButtons: R.GOAL_BUTTONS, goalsBonus: R.GOALS_BONUS,
      stickers: Object.keys(R.STICKERS), outfits: Object.keys(R.OUTFITS), shop: R.SHOP,
      fabrics: Object.fromEntries(Object.entries(R.FABRICS).map(([id, f]) => [id, f.level ? { level: f.level } : f.shop || f.club ? { shop: true } : {}])),
      clubFabrics: R.CLUB_FABRICS,
      species: Object.fromEntries(Object.entries(ST.SPECIES).map(([id, s]) => [id, s.wonder ? { page: s.page, wonder: s.wonder } : { page: s.page }])),
      pages: ST.PAGES.map((p) => ({ id: p.id, reward: p.reward })),
    };

    const sql = [];
    sql.push('-- Generated by tools/seed-sql.html from js/config.js, js/rules.js, js/stitchlings.js and js/seed.js.');
    sql.push('-- Run after supabase/schema.sql. Safe to run again: it never touches what players built.');
    sql.push('begin;');
    sql.push('');
    sql.push('-- Rule numbers, and the rest of the rules as JSON');
    sql.push(`insert into settings (id, period_minutes, commons_requires_signin, picks_per_period, surprises_per_period, bag_cap, help_bonus, wonder_per_period, block_size, plot_size, plot_stride, plot_offset, plots_per_side, surprise_pool, rules)
values (1, ${C.periodMinutes}, ${C.commonsRequiresSignIn}, ${A.picks}, ${A.surprises}, ${A.cap}, ${A.helpBonus}, ${A.wonderPerPeriod}, ${R.BLOCK}, ${R.PLOT}, ${R.PLOT_STRIDE}, ${R.PLOT_OFFSET}, ${R.PLOTS_PER_SIDE}, ${arr(R.SURPRISE_POOL)},
  ${json(rules)})
on conflict (id) do update set period_minutes = excluded.period_minutes, commons_requires_signin = excluded.commons_requires_signin,
  picks_per_period = excluded.picks_per_period, surprises_per_period = excluded.surprises_per_period, bag_cap = excluded.bag_cap,
  help_bonus = excluded.help_bonus, wonder_per_period = excluded.wonder_per_period, block_size = excluded.block_size,
  plot_size = excluded.plot_size, plot_stride = excluded.plot_stride, plot_offset = excluded.plot_offset,
  plots_per_side = excluded.plots_per_side, surprise_pool = excluded.surprise_pool, rules = excluded.rules;`);
    sql.push('');
    sql.push('-- The first four Blocks');
    sql.push(`insert into blocks (id, gx, gy, kind, name) values
${R.BLOCKS.map((b) => `  (${b.id}, ${b.gx}, ${b.gy}, ${q(b.kind)}, ${q(b.name)})`).join(',\n')}
on conflict (id) do update set gx = excluded.gx, gy = excluded.gy, kind = excluded.kind, name = excluded.name;`);
    sql.push('');
    sql.push(`-- The next ${planned} Blocks, planned ahead: the quilt grows into them as players arrive`);
    for (let i = R.BLOCKS.length; i < R.BLOCKS.length + planned; i++) {
      const b = R.blockFor(i);
      const land = S.landscapeFor(b).map((l) => [l.x, l.y, l.kind]);
      sql.push(`insert into block_plans (id, gx, gy, kind, name, landscape) values (${b.id}, ${b.gx}, ${b.gy}, ${q(b.kind)}, ${q(b.name)}, ${json(land)})
on conflict (id) do update set gx = excluded.gx, gy = excluded.gy, kind = excluded.kind, name = excluded.name, landscape = excluded.landscape;`);
    }
    sql.push('');
    sql.push('-- Wonder blueprints, and the Wonder already underway');
    for (const [id, bp] of Object.entries(R.BLUEPRINTS)) {
      sql.push(`insert into blueprints (id, name, size, rows, sprite) values (${q(id)}, ${q(bp.name)}, ${q(bp.size)}, ${arr(bp.rows)}, ${q(bp.sprite)})
on conflict (id) do update set name = excluded.name, size = excluded.size, rows = excluded.rows, sprite = excluded.sprite;`);
    }
    for (const w of R.WONDERS) {
      sql.push(`insert into wonders (id, blueprint, x, y, slots, block_id, lot, status) values (${w.id}, ${q(w.blueprint)}, ${w.x}, ${w.y}, ${R.slotsOf(w.blueprint).length}, ${w.block}, ${w.lot}, 'open')
on conflict (id) do update set blueprint = excluded.blueprint, x = excluded.x, y = excluded.y, slots = excluded.slots, block_id = excluded.block_id, lot = excluded.lot;`);
    }
    sql.push('');
    sql.push('-- Nations (a placeholder list for the prototype; see js/config.js)');
    sql.push(`insert into nations (code, name) values
${C.nations.map(([code, name]) => `  (${q(code)}, ${q(name)})`).join(',\n')}
on conflict (code) do update set name = excluded.name;`);
    sql.push('');
    sql.push('-- Name words: player names are one adjective and one noun from these lists');
    sql.push(`insert into name_words (kind, word) values
${R.WORDS.adjectives.map((w) => `  ('adjective', ${q(w)})`).concat(R.WORDS.nouns.map((w) => `  ('noun', ${q(w)})`)).join(',\n')}
on conflict do nothing;`);
    sql.push('');
    const land = S.landscape();
    sql.push(`-- The landscape of the first four Blocks: ${land.length} patches of streets, river, pond, groves and lanterns`);
    for (let i = 0; i < land.length; i += 400) {
      const chunk = land.slice(i, i + 400);
      sql.push(`insert into patches (x, y, kind) values\n${chunk.map((l) => `(${l.x},${l.y},${q(l.kind)})`).join(',')}\non conflict (x, y) do nothing;`);
    }
    sql.push('');
    sql.push('commit;');
    return sql.join('\n') + '\n';
  }

  root.QuiltSeedSql = { generate };
})(this);
